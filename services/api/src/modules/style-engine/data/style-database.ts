/**
 * StyleMate 风格知识库
 *
 * 每种风格都从五个维度进行定义：
 * 1. 骨相适配 — 脸型 / 五官线条 / 骨架粗细
 * 2. 量感适配 — 五官存在感强弱
 * 3. 体型适配 — 身形 / 身高 / 廓形偏好
 * 4. 肤色适配 — 季型 / 对比度 / 色板
 * 5. 气质适配 — 原生气质 / 生活方式
 *
 * 设计原则：没有风格绝对"不适合"任何人，只有"更容易驾驭"和"需要更多调整"之分。
 *
 * 类型定义从 @stylemate/shared 统一导入。
 */

